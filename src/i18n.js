function pickLang(pref, locales) {
  if (pref === 'ru' || pref === 'en') return pref;
  const list = (locales || []).map((l) => String(l).toLowerCase());
  // the user's top preferred language decides
  return /^(ru|uk|be|kk)\b/.test(list[0] || '') ? 'ru' : 'en';
}

function makeT(lang) {
  const dict = STRINGS[lang] || STRINGS.en;
  return (key, ...args) => {
    let s = dict[key] != null ? dict[key] : (STRINGS.en[key] != null ? STRINGS.en[key] : key);
    args.forEach((a, i) => { s = s.replace(`{${i}}`, a); });
    return s;
  };
}

module.exports = { STRINGS, pickLang, makeT };
